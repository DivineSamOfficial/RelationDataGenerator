-- Workspace schema, batch 5/5 of Part 1B: suppliers, carriers, campaigns, customers and their
-- addresses (dependency levels 3-8). Conventions: see 0101_reference.sql.

CREATE TABLE suppliers (
    supplier_id                 BIGINT UNSIGNED  NOT NULL AUTO_INCREMENT,
    supplier_code               VARCHAR(12)      NOT NULL,
    supplier_name               VARCHAR(200)     NOT NULL,
    supplier_type               VARCHAR(10)      NOT NULL,
    gst_registration_type       VARCHAR(30)      NOT NULL,
    gstin                       CHAR(15)         NULL,
    pan                         CHAR(10)         NULL,
    msme_category               VARCHAR(10)      NULL,
    payment_term_id             SMALLINT UNSIGNED NOT NULL,
    default_expense_category_id SMALLINT UNSIGNED NULL,
    contact_person_name         VARCHAR(120)     NOT NULL,
    email                       VARCHAR(150)     NOT NULL,
    phone                       VARCHAR(10)      NOT NULL,
    supplier_rating             DECIMAL(3,2)     NOT NULL,
    onboarded_date              DATE             NOT NULL,
    supplier_status             VARCHAR(30)      NOT NULL DEFAULT 'ACTIVE',
    created_at                  DATETIME(6)      NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at                  DATETIME(6)      NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    deleted_at                  DATETIME(6)      NULL,
    PRIMARY KEY (supplier_id),
    UNIQUE KEY uq_suppliers_code (supplier_code),
    UNIQUE KEY uq_suppliers_gstin (gstin),
    KEY ix_suppliers_type_status (supplier_type, supplier_status),
    CONSTRAINT fk_suppliers_payment_term FOREIGN KEY (payment_term_id) REFERENCES payment_terms (payment_term_id),
    CONSTRAINT fk_suppliers_default_expense_category FOREIGN KEY (default_expense_category_id)
        REFERENCES expense_categories (expense_category_id),
    CONSTRAINT ck_suppliers_code CHECK (REGEXP_LIKE(supplier_code, '^SUP-[0-9]{5,7}$', 'c')),
    CONSTRAINT ck_suppliers_type CHECK (REGEXP_LIKE(supplier_type, '^(GOODS|SERVICES|BOTH)$', 'c')),
    CONSTRAINT ck_suppliers_registration_type CHECK (REGEXP_LIKE(gst_registration_type, '^(REGISTERED|COMPOSITION|UNREGISTERED)$', 'c')),
    CONSTRAINT ck_suppliers_gstin_required CHECK ((gst_registration_type IN ('REGISTERED', 'COMPOSITION')) = (gstin IS NOT NULL)),
    CONSTRAINT ck_suppliers_gstin CHECK (gstin IS NULL OR REGEXP_LIKE(gstin, '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$', 'c')),
    CONSTRAINT ck_suppliers_pan CHECK (pan IS NULL OR REGEXP_LIKE(pan, '^[A-Z]{5}[0-9]{4}[A-Z]$', 'c')),
    CONSTRAINT ck_suppliers_gstin_pan CHECK (gstin IS NULL OR pan IS NULL OR SUBSTRING(gstin, 3, 10) = pan),
    CONSTRAINT ck_suppliers_msme CHECK (msme_category IS NULL OR REGEXP_LIKE(msme_category, '^(MICRO|SMALL|MEDIUM)$', 'c')),
    CONSTRAINT ck_suppliers_service_category CHECK (supplier_type = 'GOODS' OR default_expense_category_id IS NOT NULL),
    CONSTRAINT ck_suppliers_phone CHECK (REGEXP_LIKE(phone, '^[6-9][0-9]{9}$', 'c')),
    CONSTRAINT ck_suppliers_rating CHECK (supplier_rating BETWEEN 1 AND 5),
    CONSTRAINT ck_suppliers_status CHECK (REGEXP_LIKE(supplier_status, '^(ACTIVE|ON_HOLD|BLOCKED|INACTIVE)$', 'c')),
    CONSTRAINT ck_suppliers_audit CHECK (updated_at >= created_at AND (deleted_at IS NULL OR deleted_at >= created_at))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci
  COMMENT = 'Goods and service vendors in one vendor master (1B 4.5, R9)';

CREATE TABLE supplier_addresses (
    supplier_address_id         BIGINT UNSIGNED  NOT NULL AUTO_INCREMENT,
    supplier_id                 BIGINT UNSIGNED  NOT NULL,
    address_type                VARCHAR(30)      NOT NULL,
    is_default                  BOOLEAN          NOT NULL DEFAULT FALSE,
    address_line1               VARCHAR(200)     NOT NULL,
    address_line2               VARCHAR(200)     NULL,
    city                        VARCHAR(80)      NOT NULL,
    state_id                    SMALLINT UNSIGNED NOT NULL,
    pincode                     CHAR(6)          NOT NULL,
    contact_phone               VARCHAR(10)      NULL,
    previous_supplier_address_id BIGINT UNSIGNED NULL,
    valid_from                  DATE             NOT NULL,
    default_key                 VARCHAR(40)      GENERATED ALWAYS AS
        (IF(is_default AND deleted_at IS NULL, CONCAT(supplier_id, ':', address_type), NULL)) STORED,
    created_at                  DATETIME(6)      NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at                  DATETIME(6)      NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    deleted_at                  DATETIME(6)      NULL,
    PRIMARY KEY (supplier_address_id),
    UNIQUE KEY uq_supplier_addresses_default (default_key),
    UNIQUE KEY uq_supplier_addresses_previous (previous_supplier_address_id),
    KEY ix_supplier_addresses_supplier_deleted (supplier_id, deleted_at),
    CONSTRAINT fk_supplier_addresses_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (supplier_id),
    CONSTRAINT fk_supplier_addresses_state FOREIGN KEY (state_id) REFERENCES states (state_id),
    CONSTRAINT fk_supplier_addresses_previous FOREIGN KEY (previous_supplier_address_id)
        REFERENCES supplier_addresses (supplier_address_id),
    CONSTRAINT ck_supplier_addresses_type CHECK (REGEXP_LIKE(address_type, '^(REGISTERED|DISPATCH)$', 'c')),
    CONSTRAINT ck_supplier_addresses_pincode CHECK (REGEXP_LIKE(pincode, '^[1-9][0-9]{5}$', 'c')),
    CONSTRAINT ck_supplier_addresses_phone CHECK (contact_phone IS NULL OR REGEXP_LIKE(contact_phone, '^[6-9][0-9]{9}$', 'c')),
    CONSTRAINT ck_supplier_addresses_audit CHECK (updated_at >= created_at AND (deleted_at IS NULL OR deleted_at >= created_at))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci
  COMMENT = 'Supplier addresses, versioned: a change inserts a new row and soft-deletes the old (1B 4.5)';

CREATE TABLE supplier_products (
    supplier_product_id         BIGINT UNSIGNED  NOT NULL AUTO_INCREMENT,
    supplier_id                 BIGINT UNSIGNED  NOT NULL,
    product_id                  BIGINT UNSIGNED  NOT NULL,
    supplier_sku                VARCHAR(40)      NULL,
    reference_unit_cost         DECIMAL(18,4)    NOT NULL,
    minimum_order_quantity      DECIMAL(18,3)    NOT NULL,
    lead_time_days              SMALLINT UNSIGNED NOT NULL,
    is_preferred                BOOLEAN          NOT NULL DEFAULT FALSE,
    approved_date               DATE             NOT NULL,
    supplier_product_status     VARCHAR(30)      NOT NULL DEFAULT 'ACTIVE',
    preferred_key               BIGINT UNSIGNED  GENERATED ALWAYS AS
        (IF(is_preferred AND supplier_product_status = 'ACTIVE' AND deleted_at IS NULL, product_id, NULL)) STORED,
    created_at                  DATETIME(6)      NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at                  DATETIME(6)      NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    deleted_at                  DATETIME(6)      NULL,
    PRIMARY KEY (supplier_product_id),
    UNIQUE KEY uq_supplier_products_supplier_product (supplier_id, product_id),
    -- At most one active preferred supplier per product.
    UNIQUE KEY uq_supplier_products_preferred (preferred_key),
    KEY ix_supplier_products_product_status (product_id, supplier_product_status),
    CONSTRAINT fk_supplier_products_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (supplier_id),
    CONSTRAINT fk_supplier_products_product FOREIGN KEY (product_id) REFERENCES products (product_id),
    CONSTRAINT ck_supplier_products_values CHECK (
        reference_unit_cost > 0 AND minimum_order_quantity > 0 AND lead_time_days BETWEEN 1 AND 120),
    CONSTRAINT ck_supplier_products_status CHECK (REGEXP_LIKE(supplier_product_status, '^(ACTIVE|SUSPENDED|INACTIVE)$', 'c')),
    CONSTRAINT ck_supplier_products_audit CHECK (updated_at >= created_at AND (deleted_at IS NULL OR deleted_at >= created_at))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci
  COMMENT = 'Approved supplier list: who may supply which product (1B 4.5, R17)';

CREATE TABLE shipping_carriers (
    shipping_carrier_id         SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
    carrier_code                VARCHAR(12)      NOT NULL,
    carrier_name                VARCHAR(100)     NOT NULL,
    carrier_type                VARCHAR(30)      NOT NULL,
    supplier_id                 BIGINT UNSIGNED  NULL,
    supports_cod                BOOLEAN          NOT NULL DEFAULT FALSE,
    supports_reverse_pickup     BOOLEAN          NOT NULL DEFAULT FALSE,
    tracking_number_prefix      VARCHAR(6)       NOT NULL,
    tracking_url_template       VARCHAR(200)     NULL,
    is_active                   BOOLEAN          NOT NULL DEFAULT TRUE,
    created_at                  DATETIME(6)      NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at                  DATETIME(6)      NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (shipping_carrier_id),
    UNIQUE KEY uq_shipping_carriers_code (carrier_code),
    UNIQUE KEY uq_shipping_carriers_name (carrier_name),
    UNIQUE KEY uq_shipping_carriers_supplier (supplier_id),
    UNIQUE KEY uq_shipping_carriers_tracking_prefix (tracking_number_prefix),
    CONSTRAINT fk_shipping_carriers_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (supplier_id),
    CONSTRAINT ck_shipping_carriers_code CHECK (REGEXP_LIKE(carrier_code, '^[A-Z][A-Z0-9_]{1,11}$', 'c')),
    CONSTRAINT ck_shipping_carriers_type CHECK (REGEXP_LIKE(carrier_type,
        '^(EXPRESS_COURIER|SURFACE_LTL|FULL_TRUCKLOAD|HYPERLOCAL|IN_HOUSE_FLEET)$', 'c')),
    CONSTRAINT ck_shipping_carriers_vendor CHECK (carrier_type = 'IN_HOUSE_FLEET' OR supplier_id IS NOT NULL),
    CONSTRAINT ck_shipping_carriers_prefix CHECK (REGEXP_LIKE(tracking_number_prefix, '^[A-Z]{2,6}$', 'c')),
    CONSTRAINT ck_shipping_carriers_audit CHECK (updated_at >= created_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci
  COMMENT = 'Fictional logistics partners; each bills freight as a supplier (1B 4.7)';

CREATE TABLE marketing_campaigns (
    marketing_campaign_id       BIGINT UNSIGNED  NOT NULL AUTO_INCREMENT,
    campaign_code               VARCHAR(20)      NOT NULL,
    campaign_name               VARCHAR(150)     NOT NULL,
    marketing_channel_id        SMALLINT UNSIGNED NOT NULL,
    business_unit_id            SMALLINT UNSIGNED NULL,
    target_customer_type        VARCHAR(10)      NOT NULL,
    season_tag                  VARCHAR(30)      NULL,
    start_date                  DATE             NOT NULL,
    end_date                    DATE             NOT NULL,
    budget_amount               DECIMAL(18,2)    NOT NULL,
    owner_employee_id           BIGINT UNSIGNED  NOT NULL,
    campaign_status             VARCHAR(30)      NOT NULL DEFAULT 'PLANNED',
    created_at                  DATETIME(6)      NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at                  DATETIME(6)      NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (marketing_campaign_id),
    UNIQUE KEY uq_marketing_campaigns_code (campaign_code),
    KEY ix_marketing_campaigns_channel_window (marketing_channel_id, start_date, end_date),
    CONSTRAINT fk_marketing_campaigns_channel FOREIGN KEY (marketing_channel_id) REFERENCES marketing_channels (marketing_channel_id),
    CONSTRAINT fk_marketing_campaigns_business_unit FOREIGN KEY (business_unit_id) REFERENCES business_units (business_unit_id),
    CONSTRAINT fk_marketing_campaigns_owner FOREIGN KEY (owner_employee_id) REFERENCES employees (employee_id),
    CONSTRAINT ck_marketing_campaigns_code CHECK (REGEXP_LIKE(campaign_code, '^CMP-[0-9]{4}-[0-9]{3,6}$', 'c')),
    CONSTRAINT ck_marketing_campaigns_target CHECK (REGEXP_LIKE(target_customer_type, '^(B2B|B2C|ALL)$', 'c')),
    CONSTRAINT ck_marketing_campaigns_season CHECK (season_tag IS NULL OR REGEXP_LIKE(season_tag, '^[A-Z][A-Z_]{2,29}$', 'c')),
    CONSTRAINT ck_marketing_campaigns_window CHECK (end_date >= start_date),
    CONSTRAINT ck_marketing_campaigns_budget CHECK (budget_amount >= 0),
    CONSTRAINT ck_marketing_campaigns_status CHECK (REGEXP_LIKE(campaign_status, '^(PLANNED|ACTIVE|COMPLETED|CANCELLED)$', 'c')),
    CONSTRAINT ck_marketing_campaigns_audit CHECK (updated_at >= created_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci
  COMMENT = 'Campaigns with a window and budget on one marketing channel (A1 8.1)';

CREATE TABLE customers (
    customer_id                       BIGINT UNSIGNED  NOT NULL AUTO_INCREMENT,
    customer_code                     VARCHAR(12)      NOT NULL,
    customer_type                     VARCHAR(10)      NOT NULL,
    customer_segment                  VARCHAR(30)      NOT NULL,
    customer_name                     VARCHAR(200)     NOT NULL,
    contact_person_name               VARCHAR(120)     NULL,
    email                             VARCHAR(150)     NOT NULL,
    phone                             VARCHAR(10)      NOT NULL,
    gst_registration_type             VARCHAR(30)      NOT NULL,
    gstin                             CHAR(15)         NULL,
    pan                               CHAR(10)         NULL,
    payment_term_id                   SMALLINT UNSIGNED NOT NULL,
    credit_limit                      DECIMAL(18,2)    NULL,
    sales_employee_id                 BIGINT UNSIGNED  NULL,
    acquisition_marketing_channel_id  SMALLINT UNSIGNED NOT NULL,
    acquisition_marketing_campaign_id BIGINT UNSIGNED  NULL,
    acquisition_date                  DATE             NOT NULL,
    customer_status                   VARCHAR(30)      NOT NULL DEFAULT 'ACTIVE',
    created_at                        DATETIME(6)      NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at                        DATETIME(6)      NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    deleted_at                        DATETIME(6)      NULL,
    PRIMARY KEY (customer_id),
    UNIQUE KEY uq_customers_code (customer_code),
    UNIQUE KEY uq_customers_gstin (gstin),
    KEY ix_customers_type_status (customer_type, customer_status),
    KEY ix_customers_acquisition_date (acquisition_date),
    CONSTRAINT fk_customers_payment_term FOREIGN KEY (payment_term_id) REFERENCES payment_terms (payment_term_id),
    CONSTRAINT fk_customers_sales_employee FOREIGN KEY (sales_employee_id) REFERENCES employees (employee_id),
    CONSTRAINT fk_customers_acquisition_channel FOREIGN KEY (acquisition_marketing_channel_id)
        REFERENCES marketing_channels (marketing_channel_id),
    CONSTRAINT fk_customers_acquisition_campaign FOREIGN KEY (acquisition_marketing_campaign_id)
        REFERENCES marketing_campaigns (marketing_campaign_id),
    CONSTRAINT ck_customers_code CHECK (REGEXP_LIKE(customer_code, '^CUST-[0-9]{6,8}$', 'c')),
    CONSTRAINT ck_customers_type CHECK (REGEXP_LIKE(customer_type, '^(B2B|B2C)$', 'c')),
    CONSTRAINT ck_customers_segment CHECK (REGEXP_LIKE(customer_segment,
        '^(RETAILER|WHOLESALER|INSTITUTION|WORKSHOP|CORPORATE|CONSUMER)$', 'c')),
    CONSTRAINT ck_customers_consumer_segment CHECK ((customer_type = 'B2C') = (customer_segment = 'CONSUMER')),
    CONSTRAINT ck_customers_registration_type CHECK (REGEXP_LIKE(gst_registration_type,
        '^(REGISTERED|COMPOSITION|UNREGISTERED|CONSUMER)$', 'c')),
    CONSTRAINT ck_customers_consumer_registration CHECK ((customer_type = 'B2C') = (gst_registration_type = 'CONSUMER')),
    CONSTRAINT ck_customers_gstin_required CHECK ((gst_registration_type IN ('REGISTERED', 'COMPOSITION')) = (gstin IS NOT NULL)),
    CONSTRAINT ck_customers_gstin CHECK (gstin IS NULL OR REGEXP_LIKE(gstin, '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$', 'c')),
    CONSTRAINT ck_customers_pan CHECK (pan IS NULL OR REGEXP_LIKE(pan, '^[A-Z]{5}[0-9]{4}[A-Z]$', 'c')),
    CONSTRAINT ck_customers_gstin_pan CHECK (gstin IS NULL OR pan IS NULL OR SUBSTRING(gstin, 3, 10) = pan),
    CONSTRAINT ck_customers_phone CHECK (REGEXP_LIKE(phone, '^[6-9][0-9]{9}$', 'c')),
    CONSTRAINT ck_customers_credit_limit CHECK (credit_limit IS NULL OR credit_limit > 0),
    CONSTRAINT ck_customers_status CHECK (REGEXP_LIKE(customer_status, '^(ACTIVE|ON_HOLD|BLOCKED|INACTIVE)$', 'c')),
    CONSTRAINT ck_customers_audit CHECK (updated_at >= created_at AND (deleted_at IS NULL OR deleted_at >= created_at))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci
  COMMENT = 'B2B and B2C customers with first-touch attribution (1B 4.4, A1)';

CREATE TABLE customer_addresses (
    customer_address_id         BIGINT UNSIGNED  NOT NULL AUTO_INCREMENT,
    customer_id                 BIGINT UNSIGNED  NOT NULL,
    address_label               VARCHAR(60)      NOT NULL,
    is_billing_address          BOOLEAN          NOT NULL,
    is_shipping_address         BOOLEAN          NOT NULL,
    is_default_billing          BOOLEAN          NOT NULL DEFAULT FALSE,
    is_default_shipping         BOOLEAN          NOT NULL DEFAULT FALSE,
    contact_name                VARCHAR(120)     NULL,
    contact_phone               VARCHAR(10)      NULL,
    address_line1               VARCHAR(200)     NOT NULL,
    address_line2               VARCHAR(200)     NULL,
    landmark                    VARCHAR(100)     NULL,
    city                        VARCHAR(80)      NOT NULL,
    state_id                    SMALLINT UNSIGNED NOT NULL,
    pincode                     CHAR(6)          NOT NULL,
    previous_customer_address_id BIGINT UNSIGNED NULL,
    valid_from                  DATE             NOT NULL,
    default_billing_key         BIGINT UNSIGNED  GENERATED ALWAYS AS
        (IF(is_default_billing AND deleted_at IS NULL, customer_id, NULL)) STORED,
    default_shipping_key        BIGINT UNSIGNED  GENERATED ALWAYS AS
        (IF(is_default_shipping AND deleted_at IS NULL, customer_id, NULL)) STORED,
    created_at                  DATETIME(6)      NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at                  DATETIME(6)      NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    deleted_at                  DATETIME(6)      NULL,
    PRIMARY KEY (customer_address_id),
    -- At most one live default billing / shipping address per customer (1B 2.4b).
    UNIQUE KEY uq_customer_addresses_default_billing (default_billing_key),
    UNIQUE KEY uq_customer_addresses_default_shipping (default_shipping_key),
    UNIQUE KEY uq_customer_addresses_previous (previous_customer_address_id),
    -- Target of composite FKs that force an order's addresses to belong to the order's customer (D80).
    UNIQUE KEY uq_customer_addresses_id_customer (customer_address_id, customer_id),
    KEY ix_customer_addresses_customer_deleted (customer_id, deleted_at),
    KEY ix_customer_addresses_pincode (pincode),
    CONSTRAINT fk_customer_addresses_customer FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
    CONSTRAINT fk_customer_addresses_state FOREIGN KEY (state_id) REFERENCES states (state_id),
    CONSTRAINT fk_customer_addresses_previous FOREIGN KEY (previous_customer_address_id)
        REFERENCES customer_addresses (customer_address_id),
    CONSTRAINT ck_customer_addresses_usage CHECK (is_billing_address OR is_shipping_address),
    CONSTRAINT ck_customer_addresses_default_billing CHECK (NOT is_default_billing OR is_billing_address),
    CONSTRAINT ck_customer_addresses_default_shipping CHECK (NOT is_default_shipping OR is_shipping_address),
    CONSTRAINT ck_customer_addresses_pincode CHECK (REGEXP_LIKE(pincode, '^[1-9][0-9]{5}$', 'c')),
    CONSTRAINT ck_customer_addresses_phone CHECK (contact_phone IS NULL OR REGEXP_LIKE(contact_phone, '^[6-9][0-9]{9}$', 'c')),
    CONSTRAINT ck_customer_addresses_audit CHECK (updated_at >= created_at AND (deleted_at IS NULL OR deleted_at >= created_at))
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci
  COMMENT = 'Customer billing/shipping addresses, versioned like supplier addresses (1B 4.4)';
